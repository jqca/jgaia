    @app.post("/api/course-inquiry")
    def course_inquiry():
        data = request.form
        name = data.get("name", "")
        email = data.get("email", "")
        company = data.get("company", "")
        phone = data.get("phone", "")
        course = data.get("course", "")
        message = data.get("message", "")

        # スパム判定。⛔ 保存もメールもせずに、成功と同じ画面を返す
        #    （弾いたことをボットに教えない）。
        import antispam
        spam = antispam.check(request, {
            'name': name, 'email': email, 'message': message,
            antispam.HONEYPOT_FIELD: data.get(antispam.HONEYPOT_FIELD),
            'ts': data.get('ts'),
            'h-captcha-response': data.get('h-captcha-response'),
        })
        if spam:
            app.logger.info('[course-inquiry] スパムとして遮断: %s', spam)
            return redirect(url_for('thank_you')) if 'thank_you' in app.view_functions \
                else Response('お申し込みを受け付けました。', mimetype='text/plain')

        # メールより先に保存する。ここまで来た申込は、この先で何が起きても失わない。
        # 2026-07-30まで、メール送信が唯一の記録手段で、送れなければ痕跡ごと消えていた。
        try:
            save_inquiry('course', {
                'course': course, 'name': name, 'email': email,
                'company': company, 'phone': phone, 'message': message,
            })
        except Exception as e:
            app.logger.error('問い合わせの保存に失敗: %s', e)
            return Response(
                'お申し込みを受け付けられませんでした。お手数ですが '
                'info@jgaia.org までメールでご連絡ください。',
                status=500, mimetype='text/plain; charset=utf-8')

        rk = os.environ.get("RESEND_API_KEY", RESEND_API_KEY)
        if not rk:
            # 受付自体は成立しているが、確認メールは出ていない。
            # 「送信しました」と嘘をつかず、運用側にも気づけるようログに出す。
            app.logger.error(
                'RESEND_API_KEY が未設定のため確認メールを送信できませんでした'
                '（申込は保存済み）: %s / %s', name, course)
        if rk:
            try:
                import resend
                resend.api_key = rk
                body = (
                    f"コース: {course}\n"
                    f"お名前: {name}\n"
                    f"メール: {email}\n"
                    f"会社名: {company}\n"
                    f"電話: {phone}\n\n"
                    f"メッセージ:\n{message}"
                )
                from mail_targets import notify_payload
                resend.Emails.send(notify_payload(
                    f"【JGAIA講座問い合わせ】{course} - {company or name}",
                    reply_to=email, text=body))

                auto_body = (
                    f"{name} 様\n\n"
                    f"お問い合わせありがとうございます。\n"
                    f"以下の内容で受け付けました。\n\n"
                    f"コース: {course}\n\n"
                    f"担当者より2営業日以内にご連絡いたします。\n\n"
                    f"一般社団法人日本生成AI協会（JGAIA）"
                )
                resend.Emails.send({
                    "from": SENDER_EMAIL,
                    "to": [email],
                    "subject": "【JGAIA】お問い合わせありがとうございます",
                    "text": auto_body,
                })
            except Exception as e:
                # 握り潰すと「確認メールを送りました」と表示したまま誰にも届かない。
                # 申込は保存済みなので受付は成立させるが、失敗は必ず記録する。
                app.logger.error('確認メールの送信に失敗（申込は保存済み）: %s', e)

        return Response(_render_thank_you_page(course, name), mimetype="text/html")


